// versionName follows [workspace.package] version in the root Cargo.toml.
val workspaceVersion: String = rootDir.resolve("../Cargo.toml").readText()
    .substringAfter("[workspace.package]")
    .let { Regex("""(?m)^version\s*=\s*"([^"]+)"""").find(it)?.groupValues?.get(1) }
    ?: error("workspace version not found in Cargo.toml")

fun versionCodeOf(v: String): Int {
    val (major, minor, patch) = v.substringBefore('-').split('.').map { it.toInt() }
    return major * 10_000 + minor * 100 + patch
}

