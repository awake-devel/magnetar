//! Hard illegal-content blocklist (ARCHITECTURE.md D53, D68; docs/DHT.md §7). Pure, no feature:
//! the server's DHT crawler, the server's Nostr ingest and the phone's ingest all use it.
//!
//! **Binding rule**: nothing here logs, stores or returns the text it reads. A verdict carries
//! only the tier of the rule that fired, never the matched term or the input.
//!
//! Input text is normalised: Unicode NFKC, invisible characters and leftover combining marks
//! removed (not separators), Unicode lowercase, Latin diacritics folded, everything else that
//! is not a letter or digit becomes a separator; a second variant undoes common digit/symbol
//! substitutions (0→o, 1→i, 3→e, 4→a, 5→s, @→a) and Cyrillic/Greek look-alikes, and each
//! variant's collapsed form joins runs of one-character tokens (D71). Every token and every token 2-
//! and 3-gram of each variant is hashed (`sha256("magnetar-blocklist-v1:" + ngram)`) and looked
//! up in two sets:
//! - **hard** terms block on their own;
//! - **context** terms block only an adult torrent, as does the structural age rule (a number
//!   1–17 next to an ordinary-word age marker, [`age_mark`]); an explicit age annotation
//!   (`12 yo`, `12 years old`) next to a minor age blocks any torrent.
//!
//! The built-in list is `terms.v1` (hashes only, generated by `scripts/blocklist-hash.sh` from a
//! plain-text source that is not committed). [`Blocklist::with_extra`] adds terms from
//! `MAGNETAR_BLOCKLIST_FILE`; nothing can remove one.

use std::collections::HashSet;
use std::hash::{BuildHasher, Hasher, RandomState};
use std::sync::OnceLock;

use sha2::{Digest, Sha256};
use unicode_normalization::UnicodeNormalization;
use unicode_normalization::char::is_combining_mark;

/// The built-in list, `hard|context <sha256 hex>` per line.
pub const BUILTIN: &str = include_str!("terms.v1");
/// Version of the built-in list: recorded in `blocked_infohashes.rule_version`; a sweep of
/// stored data runs when `meta.dht_blocklist_version` is below it (stage 5).
pub const BUILTIN_VERSION: i16 = 1;
/// Prefix of every hashed n-gram (domain separation; changing it invalidates every list).
pub const HASH_PREFIX: &str = "magnetar-blocklist-v1:";
/// Longest phrase a term may have, in tokens (the n-grams looked up).
pub const MAX_NGRAM: usize = 3;
/// Ages below this, next to an age marker in an adult torrent, block (minors).
pub const AGE_LIMIT: u32 = 18;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Tier {
    Hard,
    Context,
    /// The structural age rule (adult torrents only).
    Age,
}

impl Tier {
    pub fn as_str(self) -> &'static str {
        match self {
            Tier::Hard => "hard",
            Tier::Context => "context",
            Tier::Age => "age",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Verdict {
    Allow,
    /// Never carries the matched text: counts are kept by tier only.
    Block(Tier),
}

impl Verdict {
    pub fn is_block(self) -> bool {
        matches!(self, Verdict::Block(_))
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum LoadError {
    /// Line number (1-based) of a malformed line; the line itself is not echoed.
    BadLine(usize),
    Empty,
}

impl std::fmt::Display for LoadError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            LoadError::BadLine(n) => write!(f, "blocklist: malformed line {n}"),
            LoadError::Empty => write!(f, "blocklist: no terms"),
        }
    }
}

impl std::error::Error for LoadError {}

type Hash = [u8; 32];

/// What the screens check against. Cheap to share (`Arc` or the [`global`] one).
#[derive(Clone, Default)]
pub struct Blocklist {
    hard: HashSet<Hash>,
    context: HashSet<Hash>,
    version: i16,
}

// No Debug of the sets: hashes of such terms do not belong in logs either.
impl std::fmt::Debug for Blocklist {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Blocklist")
            .field("hard", &self.hard.len())
            .field("context", &self.context.len())
            .field("version", &self.version)
            .finish()
    }
}

/// Hash of one normalised phrase (tokens joined by one space).
pub fn term_hash(phrase: &str) -> Hash {
    let mut h = Sha256::new();
    h.update(HASH_PREFIX.as_bytes());
    h.update(phrase.as_bytes());
    h.finalize().into()
}

impl Blocklist {
    /// The built-in list ([`BUILTIN`], [`BUILTIN_VERSION`]).
    pub fn builtin() -> Result<Self, LoadError> {
        Self::parse_hashed(BUILTIN, BUILTIN_VERSION)
    }

    /// A list in the `terms.v1` format: `hard <hex>` / `context <hex>`, `#` comments.
    pub fn parse_hashed(text: &str, version: i16) -> Result<Self, LoadError> {
        let mut b = Blocklist {
            version,
            ..Default::default()
        };
        for (i, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (tier, hex_hash) = line.split_once(' ').ok_or(LoadError::BadLine(i + 1))?;
            let mut h = [0u8; 32];
            hex::decode_to_slice(hex_hash.trim(), &mut h).map_err(|_| LoadError::BadLine(i + 1))?;
            match tier {
                "hard" => b.hard.insert(h),
                "context" => b.context.insert(h),
                _ => return Err(LoadError::BadLine(i + 1)),
            };
        }
        if b.hard.is_empty() && b.context.is_empty() {
            return Err(LoadError::Empty);
        }
        Ok(b)
    }

    /// Plain terms (one per line, `context:` prefix for the context tier, `#` comments), as
    /// `MAGNETAR_BLOCKLIST_FILE` holds them. Each term is normalised like the input; a term of
    /// more than [`MAX_NGRAM`] tokens, or with none, is an error.
    pub fn add_plain(&mut self, text: &str) -> Result<usize, LoadError> {
        let mut n = 0;
        for (i, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (context, term) = match line.strip_prefix("context:") {
                Some(t) => (true, t),
                None => (false, line.strip_prefix("hard:").unwrap_or(line)),
            };
            let toks = tokens(&base_text(term));
            let cjk = toks.len() == 1 && toks[0].chars().all(is_cjk);
            let chars = toks.first().map_or(0, |t| t.chars().count());
            if toks.is_empty()
                || toks.len() > MAX_NGRAM
                || (cjk && !(2..=MAX_CJK_GRAM).contains(&chars))
            {
                return Err(LoadError::BadLine(i + 1));
            }
            let h = term_hash(&toks.join(" "));
            if context {
                self.context.insert(h);
            } else {
                self.hard.insert(h);
            }
            n += 1;
        }
        Ok(n)
    }

    /// This list plus plain extra terms: only ever adds.
    pub fn with_extra(mut self, plain: &str) -> Result<Self, LoadError> {
        self.add_plain(plain)?;
        Ok(self)
    }

    pub fn version(&self) -> i16 {
        self.version
    }

    pub fn len(&self) -> (usize, usize) {
        (self.hard.len(), self.context.len())
    }

    pub fn is_empty(&self) -> bool {
        self.hard.is_empty() && self.context.is_empty()
    }

    /// Verdict over `texts` (both tiers) and `hard_only` (hard tier only: Nostr descriptions and
    /// hashtags). `adult` = the torrent is adult (classifier, or a Nostr `porn` category): only
    /// then do context terms and the age rule apply.
    ///
    /// Streaming: n-grams are hashed as the tokens go by and nothing is kept, so memory stays
    /// proportional to one text (hostile 16 MiB info dicts included, D71).
    pub fn check<S: AsRef<str>, T: AsRef<str>>(
        &self,
        texts: &[S],
        hard_only: &[T],
        adult: bool,
    ) -> Verdict {
        let mut prefix = Sha256::new();
        prefix.update(HASH_PREFIX.as_bytes());
        let mut st = ScanState {
            list: self,
            prefix,
            context_hit: false,
            age: None,
            seen: HashSet::new(),
            keys: RandomState::new(),
        };
        for t in texts {
            if st.text(t.as_ref(), true) {
                return Verdict::Block(Tier::Hard);
            }
        }
        for t in hard_only {
            if st.text(t.as_ref(), false) {
                return Verdict::Block(Tier::Hard);
            }
        }
        if adult && st.context_hit {
            return Verdict::Block(Tier::Context);
        }
        match st.age {
            Some(AgeMark::Explicit) => return Verdict::Block(Tier::Age),
            Some(AgeMark::Contextual) if adult => return Verdict::Block(Tier::Age),
            _ => {}
        }
        Verdict::Allow
    }
}

/// Grams already looked up, by a keyed 64-bit hash (random keys per check, so an input cannot
/// be built to collide with a term). Bounded: past this many, grams are simply hashed again.
const SEEN_MAX: usize = 1 << 19;

struct ScanState<'a> {
    list: &'a Blocklist,
    prefix: Sha256,
    context_hit: bool,
    age: Option<AgeMark>,
    seen: HashSet<u64>,
    keys: RandomState,
}

impl ScanState<'_> {
    /// Look up one hash; true = hard hit.
    fn hit(&mut self, h: Sha256, both: bool) -> bool {
        let d: Hash = h.finalize().into();
        if self.list.hard.contains(&d) {
            return true;
        }
        if both && !self.context_hit && self.list.context.contains(&d) {
            self.context_hit = true;
        }
        false
    }

    /// True when this gram was looked up before in this check (texts are scanned before
    /// hard-only ones, so an earlier lookup covered at least the tiers this one needs).
    fn seen_before<'b>(&mut self, parts: impl Iterator<Item = &'b [u8]>) -> bool {
        let mut k = self.keys.build_hasher();
        for p in parts {
            k.write(p);
            k.write_u8(0xff);
        }
        let k = k.finish();
        if self.seen.contains(&k) {
            return true;
        }
        if self.seen.len() < SEEN_MAX {
            self.seen.insert(k);
        }
        false
    }

    fn gram(&mut self, parts: &[&str], both: bool) -> bool {
        if self.seen_before(parts.iter().map(|p| p.as_bytes())) {
            return false;
        }
        let mut h = self.prefix.clone();
        for (i, p) in parts.iter().enumerate() {
            if i > 0 {
                h.update(b" ");
            }
            h.update(p.as_bytes());
        }
        self.hit(h, both)
    }

    /// Character 2- to [`MAX_CJK_GRAM`]-grams of every CJK run inside `token`, streamed (the
    /// byte offsets of the last three CJK characters of the current run are all it keeps).
    fn cjk(&mut self, token: &str, both: bool) -> bool {
        let mut starts = [0usize; MAX_CJK_GRAM - 1];
        let mut run = 0usize; // CJK characters in the current run
        for (at, c) in token.char_indices() {
            if !is_cjk(c) {
                run = 0;
                continue;
            }
            let end = at + c.len_utf8();
            for back in 1..=run.min(MAX_CJK_GRAM - 1) {
                let from = starts[MAX_CJK_GRAM - 1 - back];
                let g = &token.as_bytes()[from..end];
                // CJK grams share the cache with tokens; the 0x01 part keeps them apart.
                if self.seen_before([b"\x01".as_slice(), g].into_iter()) {
                    continue;
                }
                let mut h = self.prefix.clone();
                h.update(g);
                if self.hit(h, both) {
                    return true;
                }
            }
            starts.rotate_left(1);
            starts[MAX_CJK_GRAM - 2] = at;
            run += 1;
        }
        false
    }

    /// One input text, every variant. True = hard hit.
    fn text(&mut self, text: &str, both: bool) -> bool {
        for (variant, with_age) in variants(text) {
            let age = both && with_age && self.age != Some(AgeMark::Explicit);
            // The last three tokens, oldest first.
            let mut win: [&str; MAX_NGRAM] = [""; MAX_NGRAM];
            let mut k = 0usize;
            for tok in variant.split_whitespace() {
                win.rotate_left(1);
                win[MAX_NGRAM - 1] = tok;
                k += 1;
                for n in 1..=k.min(MAX_NGRAM) {
                    if self.gram(&win[MAX_NGRAM - n..], both) {
                        return true;
                    }
                }
                if tok.chars().any(is_cjk) && self.cjk(tok, both) {
                    return true;
                }
                if age && k >= 3 {
                    self.age = self.age.max(mark_at(win[0], Some(win[1]), Some(win[2])));
                }
            }
            if age {
                // The last two positions (and every position of a text under three tokens).
                if k >= 2 {
                    let t = &win[MAX_NGRAM - 2..];
                    self.age = self.age.max(mark_at(t[0], Some(t[1]), None));
                }
                if k >= 1 {
                    self.age = self.age.max(mark_at(win[MAX_NGRAM - 1], None, None));
                }
            }
        }
        false
    }
}

static GLOBAL: OnceLock<Option<Blocklist>> = OnceLock::new();

/// Install the process-wide list (the built-in one plus `MAGNETAR_BLOCKLIST_FILE`), once, at
/// start. Returns false when one was already installed (or [`global`] already ran), in which
/// case the call changes nothing.
pub fn install(b: Blocklist) -> bool {
    GLOBAL.set(Some(b)).is_ok()
}

/// The process-wide list: the installed one, else the built-in one. None only if the
/// built-in list does not load, which callers treat as "block everything" (fail closed).
pub fn global() -> Option<&'static Blocklist> {
    GLOBAL.get_or_init(|| Blocklist::builtin().ok()).as_ref()
}

/// Lowercase, fold Latin diacritics; any other character kept as is.
fn fold_char(c: char, out: &mut String, homoglyphs: bool) {
    for l in c.to_lowercase() {
        let l = if homoglyphs { homoglyph(l) } else { l };
        let s = match l {
            'à' | 'á' | 'â' | 'ã' | 'ä' | 'å' | 'ā' | 'ă' | 'ą' => "a",
            'æ' => "ae",
            'ç' | 'ć' | 'ĉ' | 'ċ' | 'č' => "c",
            'ď' | 'đ' | 'ð' => "d",
            'è' | 'é' | 'ê' | 'ë' | 'ē' | 'ĕ' | 'ė' | 'ę' | 'ě' => "e",
            'ĝ' | 'ğ' | 'ġ' | 'ģ' => "g",
            'ĥ' | 'ħ' => "h",
            'ì' | 'í' | 'î' | 'ï' | 'ĩ' | 'ī' | 'ĭ' | 'į' | 'ı' => "i",
            'ĵ' => "j",
            'ķ' => "k",
            'ĺ' | 'ļ' | 'ľ' | 'ŀ' | 'ł' => "l",
            'ñ' | 'ń' | 'ņ' | 'ň' => "n",
            'ò' | 'ó' | 'ô' | 'õ' | 'ö' | 'ø' | 'ō' | 'ŏ' | 'ő' => "o",
            'œ' => "oe",
            'ŕ' | 'ŗ' | 'ř' => "r",
            'ś' | 'ŝ' | 'ş' | 'š' | 'ș' => "s",
            'ß' => "ss",
            'ţ' | 'ť' | 'ŧ' | 'ț' => "t",
            'þ' => "th",
            'ù' | 'ú' | 'û' | 'ü' | 'ũ' | 'ū' | 'ŭ' | 'ů' | 'ű' | 'ų' => "u",
            'ŵ' => "w",
            'ý' | 'ÿ' | 'ŷ' => "y",
            'ź' | 'ż' | 'ž' => "z",
            _ => {
                out.push(l);
                continue;
            }
        };
        out.push_str(s);
    }
}

/// Cyrillic and Greek letters that look like Latin ones (lowercase), for the substitution
/// variant: `zоrblax` with a Cyrillic `о` reads as the Latin word.
fn homoglyph(c: char) -> char {
    match c {
        'а' | 'α' => 'a',
        'е' | 'ё' | 'ε' => 'e',
        'о' | 'ο' => 'o',
        'р' | 'ρ' => 'p',
        'с' | 'ϲ' => 'c',
        'у' => 'y',
        'х' | 'χ' => 'x',
        'і' | 'ї' | 'ι' => 'i',
        'ј' => 'j',
        'ѕ' => 's',
        'һ' => 'h',
        'ԁ' => 'd',
        'ԛ' => 'q',
        'ԝ' => 'w',
        'ӏ' => 'l',
        'к' | 'κ' => 'k',
        'м' => 'm',
        'т' | 'τ' => 't',
        'ν' => 'v',
        'υ' => 'u',
        'ɡ' => 'g',
        c => c,
    }
}

/// Invisible characters that must not split a word: format characters (zero-width space and
/// joiners, soft hyphen, bidi controls, word joiner, BOM, variation selectors, tags, Hangul
/// fillers) and controls other than whitespace (`NUL`: the stored title drops it, so the
/// screen must read `a\0b` as `ab`).
fn ignorable(c: char) -> bool {
    (c.is_control() && !c.is_whitespace())
        || matches!(c as u32,
            0x00AD | 0x034F | 0x061C | 0x115F | 0x1160 | 0x17B4 | 0x17B5
            | 0x180B..=0x180F | 0x200B..=0x200F | 0x202A..=0x202E | 0x2060..=0x206F
            | 0x3164 | 0xFE00..=0xFE0F | 0xFEFF | 0xFFA0 | 0xFFF0..=0xFFF8
            | 0x1BCA0..=0x1BCA3 | 0x1D173..=0x1D17A | 0xE0000..=0xE0FFF)
}

/// NFKC (fullwidth, circled, mathematical and other compatibility letters become plain ones;
/// a letter + combining accent becomes the precomposed letter), invisible characters and
/// remaining combining marks removed, every other non letter/digit a separator; `leet` also
/// reads digits/symbols and Latin look-alikes as letters.
fn normal_text(s: &str, leet: bool) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.nfkc() {
        if ignorable(c) || is_combining_mark(c) {
            continue;
        }
        let c = if leet {
            match c {
                '0' => 'o',
                '1' => 'i',
                '3' => 'e',
                '4' => 'a',
                '5' => 's',
                '@' => 'a',
                c => c,
            }
        } else {
            c
        };
        if c.is_alphanumeric() {
            fold_char(c, &mut out, leet);
        } else {
            out.push(' ');
        }
    }
    out
}

/// Folded text with every non letter/digit as a space (the base variant).
fn base_text(s: &str) -> String {
    normal_text(s, false)
}

/// The substitution variant: digits/symbols and Latin look-alikes read as letters.
fn leet_text(s: &str) -> String {
    normal_text(s, true)
}

/// Runs of two or more one-character tokens joined (`z.o.r.b` → `zorb`); None when there is
/// no such run.
fn collapsed(s: &str) -> Option<String> {
    let toks: Vec<&str> = s.split_whitespace().collect();
    let single = |t: &str| t.chars().nth(1).is_none();
    let mut out = String::with_capacity(s.len());
    let mut changed = false;
    let mut i = 0;
    while i < toks.len() {
        if !out.is_empty() {
            out.push(' ');
        }
        let mut j = i;
        while j < toks.len() && single(toks[j]) {
            j += 1;
        }
        if j - i >= 2 {
            changed = true;
            for t in &toks[i..j] {
                out.push_str(t);
            }
            i = j;
        } else {
            out.push_str(toks[i]);
            i += 1;
        }
    }
    changed.then_some(out)
}

/// What the matcher scans: the base variant, the substitution variant when it differs, and
/// each one's collapsed form when it has one. The flag says whether the age rule reads it (not
/// the collapsed forms: `x 1 2 y o` must not read as `12yo`).
fn variants(s: &str) -> Vec<(String, bool)> {
    let base = base_text(s);
    let leet = leet_text(s);
    let mut out = Vec::with_capacity(4);
    let cb = collapsed(&base);
    let cl = if leet == base { None } else { collapsed(&leet) };
    let leet_differs = leet != base;
    out.push((base, true));
    if let Some(c) = cb {
        out.push((c, false));
    }
    if leet_differs {
        out.push((leet, true));
    }
    if let Some(c) = cl {
        out.push((c, false));
    }
    out
}

fn tokens(s: &str) -> Vec<String> {
    s.split_whitespace().map(str::to_string).collect()
}

/// The token lists of the base and substitution variants (the classifier's word lookup; the
/// blocklist itself also scans collapsed forms, [`Blocklist::check`]).
pub fn normalize(s: &str) -> Vec<Vec<String>> {
    let base = tokens(&base_text(s));
    let leet = tokens(&leet_text(s));
    if leet == base {
        vec![base]
    } else {
        vec![base, leet]
    }
}

/// Every 1-, 2- and 3-gram of `toks`, tokens joined by one space.
pub fn ngrams(toks: &[String]) -> Vec<String> {
    let mut out = Vec::with_capacity(toks.len() * MAX_NGRAM);
    for i in 0..toks.len() {
        let mut g = String::new();
        for (n, t) in toks[i..].iter().take(MAX_NGRAM).enumerate() {
            if n > 0 {
                g.push(' ');
            }
            g.push_str(t);
            out.push(g.clone());
        }
    }
    out
}

/// Han, kana and hangul: scripts written without spaces between words.
pub fn is_cjk(c: char) -> bool {
    matches!(c as u32,
        0x3040..=0x30FF   // hiragana, katakana
        | 0x3400..=0x4DBF // CJK extension A
        | 0x4E00..=0x9FFF // CJK unified ideographs
        | 0xF900..=0xFAFF // CJK compatibility ideographs
        | 0xAC00..=0xD7AF // hangul syllables
        | 0x20000..=0x2A6DF)
}

/// Longest CJK character n-gram looked up (terms of these scripts are 2–4 characters).
pub const MAX_CJK_GRAM: usize = 4;

/// Character 2- to 4-grams of every CJK run inside `token`: those scripts have no spaces, so a
/// whole sentence is one token and a term can only be found inside it. Empty for other text.
pub fn cjk_grams(token: &str) -> Vec<String> {
    let mut out = Vec::new();
    let chars: Vec<char> = token.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        if !is_cjk(chars[i]) {
            i += 1;
            continue;
        }
        let start = i;
        while i < chars.len() && is_cjk(chars[i]) {
            i += 1;
        }
        let run = &chars[start..i];
        for a in 0..run.len() {
            for n in 2..=MAX_CJK_GRAM {
                if a + n > run.len() {
                    break;
                }
                out.push(run[a..a + n].iter().collect());
            }
        }
    }
    out
}

/// How an age below [`AGE_LIMIT`] is written next to its marker.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum AgeMark {
    /// `yrs`, `aged 12`, `age 12`, French `ans`, German `jahre`, Spanish/Portuguese `anos`:
    /// also ordinary title words, so they block adult torrents only.
    Contextual,
    /// `12 yo`, `12yo`, `12 y o`, `12 years old`, `12yrs old`: an age annotation, which blocks
    /// any torrent (a photo set labelled with a child's age carries no adult word; stage 3 live
    /// sample, D68).
    Explicit,
}

fn minor(t: &str) -> bool {
    t.len() <= 2
        && t.bytes().all(|b| b.is_ascii_digit())
        && t.parse::<u32>().is_ok_and(|n| (1..AGE_LIMIT).contains(&n))
}

/// The age mark of token `t` followed by `n1`, `n2`.
fn mark_at(t: &str, n1: Option<&str>, n2: Option<&str>) -> Option<AgeMark> {
    let digits = t.bytes().take_while(u8::is_ascii_digit).count();
    let rest = &t[digits..];
    if digits > 0 && minor(&t[..digits]) && !rest.is_empty() {
        // Glued: `12yo`, `12yrs old`, `12yearold`.
        match rest {
            "yo" | "yearold" | "yearsold" => Some(AgeMark::Explicit),
            "yrs" | "yr" if n1 == Some("old") => Some(AgeMark::Explicit),
            "yrs" | "yr" => Some(AgeMark::Contextual),
            _ => None,
        }
    } else if minor(t) {
        match n1 {
            Some("yo") => Some(AgeMark::Explicit),
            Some("y") if n2 == Some("o") => Some(AgeMark::Explicit),
            Some("years" | "year" | "yrs" | "yr") if n2 == Some("old") => Some(AgeMark::Explicit),
            Some("yrs" | "yr" | "ans" | "jahre" | "anos") => Some(AgeMark::Contextual),
            _ => None,
        }
    } else if matches!(t, "aged" | "age") && n1.is_some_and(minor) {
        Some(AgeMark::Contextual)
    } else {
        None
    }
}

/// An age below [`AGE_LIMIT`] next to an age marker, the strongest form found.
pub fn age_mark(toks: &[String]) -> Option<AgeMark> {
    let mut found = None;
    for (i, t) in toks.iter().enumerate() {
        let next = |k: usize| toks.get(i + k).map(String::as_str);
        found = found.max(mark_at(t, next(1), next(2)));
        if found == Some(AgeMark::Explicit) {
            break;
        }
    }
    found
}

/// Any minor age next to a marker ([`age_mark`]).
pub fn age_rule(toks: &[String]) -> bool {
    age_mark(toks).is_some()
}

