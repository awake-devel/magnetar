//! Hard illegal-content blocklist (ARCHITECTURE.md D53, D68; docs/DHT.md §7). Pure, no feature:
//! the server's DHT crawler, the server's Nostr ingest and the phone's ingest all use it.
//!
//! **Binding rule**: nothing here logs, stores or returns the text it reads. A verdict carries
//! only the tier of the rule that fired, never the matched term or the input.
//!
//! Input text is normalised ([`normalize`]): Unicode lowercase, Latin diacritics folded,
//! everything that is not a letter or digit becomes a separator; a second variant undoes common
//! digit/symbol substitutions (0→o, 1→i, 3→e, 4→a, 5→s, @→a). Every token and every token 2-
//! and 3-gram of each variant is hashed (`sha256("magnetar-blocklist-v1:" + ngram)`) and looked
//! up in two sets:
//! - **hard** terms block on their own;
//! - **context** terms block only an adult torrent, as does the structural age rule (a number
//!   1–17 next to an age marker, [`age_rule`]).
//!
//! The built-in list is `terms.v1` (hashes only, generated by `scripts/blocklist-hash.sh` from a
//! plain-text source that is not committed). [`Blocklist::with_extra`] adds terms from
//! `MAGNETAR_BLOCKLIST_FILE`; nothing can remove one.

use std::collections::HashSet;
use std::sync::OnceLock;

use sha2::{Digest, Sha256};

/// The built-in list, `hard|context <sha256 hex>` per line.
pub const BUILTIN: &str = include_str!("terms.v1");
/// Version of the built-in list: recorded in `blocked_infohashes.rule_version`; a sweep of
/// stored data runs when `meta.dht_blocklist_version` is below it (stage 5).
pub const BUILTIN_VERSION: i16 = 1;
/// Prefix of every hashed n-gram (domain separation; changing it invalidates every list).
pub const HASH_PREFIX: &str = "magnetar-blocklist-v1:";
/// Longest phrase a term may have, in tokens (the n-grams looked up).
pub const MAX_NGRAM: usize = 3;
/// Ages below this, next to an age marker in an adult torrent, block (minors).
pub const AGE_LIMIT: u32 = 18;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Tier {
    Hard,
    Context,
    /// The structural age rule (adult torrents only).
    Age,
}

impl Tier {
    pub fn as_str(self) -> &'static str {
        match self {
            Tier::Hard => "hard",
            Tier::Context => "context",
            Tier::Age => "age",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Verdict {
    Allow,
    /// Never carries the matched text: counts are kept by tier only.
    Block(Tier),
}

impl Verdict {
    pub fn is_block(self) -> bool {
        matches!(self, Verdict::Block(_))
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum LoadError {
    /// Line number (1-based) of a malformed line; the line itself is not echoed.
    BadLine(usize),
    Empty,
}

impl std::fmt::Display for LoadError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            LoadError::BadLine(n) => write!(f, "blocklist: malformed line {n}"),
            LoadError::Empty => write!(f, "blocklist: no terms"),
        }
    }
}

impl std::error::Error for LoadError {}

type Hash = [u8; 32];

/// What the screens check against. Cheap to share (`Arc` or the [`global`] one).
#[derive(Clone, Default)]
pub struct Blocklist {
    hard: HashSet<Hash>,
    context: HashSet<Hash>,
    version: i16,
}

// No Debug of the sets: hashes of such terms do not belong in logs either.
impl std::fmt::Debug for Blocklist {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Blocklist")
            .field("hard", &self.hard.len())
            .field("context", &self.context.len())
            .field("version", &self.version)
            .finish()
    }
}

/// Hash of one normalised phrase (tokens joined by one space).
pub fn term_hash(phrase: &str) -> Hash {
    let mut h = Sha256::new();
    h.update(HASH_PREFIX.as_bytes());
    h.update(phrase.as_bytes());
    h.finalize().into()
}

impl Blocklist {
    /// The built-in list ([`BUILTIN`], [`BUILTIN_VERSION`]).
    pub fn builtin() -> Result<Self, LoadError> {
        Self::parse_hashed(BUILTIN, BUILTIN_VERSION)
    }

    /// A list in the `terms.v1` format: `hard <hex>` / `context <hex>`, `#` comments.
    pub fn parse_hashed(text: &str, version: i16) -> Result<Self, LoadError> {
        let mut b = Blocklist {
            version,
            ..Default::default()
        };
        for (i, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (tier, hex_hash) = line.split_once(' ').ok_or(LoadError::BadLine(i + 1))?;
            let mut h = [0u8; 32];
            hex::decode_to_slice(hex_hash.trim(), &mut h).map_err(|_| LoadError::BadLine(i + 1))?;
            match tier {
                "hard" => b.hard.insert(h),
                "context" => b.context.insert(h),
                _ => return Err(LoadError::BadLine(i + 1)),
            };
        }
        if b.hard.is_empty() && b.context.is_empty() {
            return Err(LoadError::Empty);
        }
        Ok(b)
    }

    /// Plain terms (one per line, `context:` prefix for the context tier, `#` comments), as
    /// `MAGNETAR_BLOCKLIST_FILE` holds them. Each term is normalised like the input; a term of
    /// more than [`MAX_NGRAM`] tokens, or with none, is an error.
    pub fn add_plain(&mut self, text: &str) -> Result<usize, LoadError> {
        let mut n = 0;
        for (i, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let (context, term) = match line.strip_prefix("context:") {
                Some(t) => (true, t),
                None => (false, line.strip_prefix("hard:").unwrap_or(line)),
            };
            let toks = tokens(&base_text(term));
            if toks.is_empty() || toks.len() > MAX_NGRAM {
                return Err(LoadError::BadLine(i + 1));
            }
            let h = term_hash(&toks.join(" "));
            if context {
                self.context.insert(h);
            } else {
                self.hard.insert(h);
            }
            n += 1;
        }
        Ok(n)
    }

    /// This list plus plain extra terms: only ever adds.
    pub fn with_extra(mut self, plain: &str) -> Result<Self, LoadError> {
        self.add_plain(plain)?;
        Ok(self)
    }

    pub fn version(&self) -> i16 {
        self.version
    }

    pub fn len(&self) -> (usize, usize) {
        (self.hard.len(), self.context.len())
    }

    pub fn is_empty(&self) -> bool {
        self.hard.is_empty() && self.context.is_empty()
    }

    /// Verdict over `texts` (both tiers) and `hard_only` (hard tier only: Nostr descriptions and
    /// hashtags). `adult` = the torrent is adult (classifier, or a Nostr `porn` category): only
    /// then do context terms and the age rule apply.
    pub fn check<S: AsRef<str>, T: AsRef<str>>(
        &self,
        texts: &[S],
        hard_only: &[T],
        adult: bool,
    ) -> Verdict {
        let mut seen: HashSet<String> = HashSet::new();
        let mut context_hit = false;
        let mut age_hit = false;
        let mut scan = |text: &str, both: bool| -> bool {
            for variant in normalize(text) {
                if both && adult && !age_hit && age_rule(&variant) {
                    age_hit = true;
                }
                for g in ngrams(&variant) {
                    if !seen.insert(g.clone()) {
                        continue;
                    }
                    let h = term_hash(&g);
                    if self.hard.contains(&h) {
                        return true;
                    }
                    if both && self.context.contains(&h) {
                        context_hit = true;
                    }
                }
            }
            false
        };
        for t in texts {
            if scan(t.as_ref(), true) {
                return Verdict::Block(Tier::Hard);
            }
        }
        // A hard-only text whose n-grams were already seen in `texts` was already checked
        // against the hard set; dedupe across both is therefore sound.
        for t in hard_only {
            if scan(t.as_ref(), false) {
                return Verdict::Block(Tier::Hard);
            }
        }
        if adult && context_hit {
            return Verdict::Block(Tier::Context);
        }
        if adult && age_hit {
            return Verdict::Block(Tier::Age);
        }
        Verdict::Allow
    }
}

static GLOBAL: OnceLock<Option<Blocklist>> = OnceLock::new();

/// Install the process-wide list (the built-in one plus `MAGNETAR_BLOCKLIST_FILE`), once, at
/// start. Returns false when one was already installed (or [`global`] already ran), in which
/// case the call changes nothing.
pub fn install(b: Blocklist) -> bool {
    GLOBAL.set(Some(b)).is_ok()
}

/// The process-wide list: the installed one, else the built-in one. None only if the
/// built-in list does not load, which callers treat as "block everything" (fail closed).
pub fn global() -> Option<&'static Blocklist> {
    GLOBAL.get_or_init(|| Blocklist::builtin().ok()).as_ref()
}

/// Lowercase, fold Latin diacritics; any other character kept as is.
fn fold_char(c: char, out: &mut String) {
    for l in c.to_lowercase() {
        let s = match l {
            'à' | 'á' | 'â' | 'ã' | 'ä' | 'å' | 'ā' | 'ă' | 'ą' => "a",
            'æ' => "ae",
            'ç' | 'ć' | 'ĉ' | 'ċ' | 'č' => "c",
            'ď' | 'đ' | 'ð' => "d",
            'è' | 'é' | 'ê' | 'ë' | 'ē' | 'ĕ' | 'ė' | 'ę' | 'ě' => "e",
            'ĝ' | 'ğ' | 'ġ' | 'ģ' => "g",
            'ĥ' | 'ħ' => "h",
            'ì' | 'í' | 'î' | 'ï' | 'ĩ' | 'ī' | 'ĭ' | 'į' | 'ı' => "i",
            'ĵ' => "j",
            'ķ' => "k",
            'ĺ' | 'ļ' | 'ľ' | 'ŀ' | 'ł' => "l",
            'ñ' | 'ń' | 'ņ' | 'ň' => "n",
            'ò' | 'ó' | 'ô' | 'õ' | 'ö' | 'ø' | 'ō' | 'ŏ' | 'ő' => "o",
            'œ' => "oe",
            'ŕ' | 'ŗ' | 'ř' => "r",
            'ś' | 'ŝ' | 'ş' | 'š' | 'ș' => "s",
            'ß' => "ss",
            'ţ' | 'ť' | 'ŧ' | 'ț' => "t",
            'þ' => "th",
            'ù' | 'ú' | 'û' | 'ü' | 'ũ' | 'ū' | 'ŭ' | 'ů' | 'ű' | 'ų' => "u",
            'ŵ' => "w",
            'ý' | 'ÿ' | 'ŷ' => "y",
            'ź' | 'ż' | 'ž' => "z",
            _ => {
                out.push(l);
                continue;
            }
        };
        out.push_str(s);
    }
}

/// Folded text with every non letter/digit as a space (the base variant).
fn base_text(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if c.is_alphanumeric() {
            fold_char(c, &mut out);
        } else {
            out.push(' ');
        }
    }
    out
}

/// The substitution variant: digits/symbols read as letters, then like [`base_text`].
fn leet_text(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        let c = match c {
            '0' => 'o',
            '1' => 'i',
            '3' => 'e',
            '4' => 'a',
            '5' => 's',
            '@' => 'a',
            c => c,
        };
        if c.is_alphanumeric() {
            fold_char(c, &mut out);
        } else {
            out.push(' ');
        }
    }
    out
}

fn tokens(s: &str) -> Vec<String> {
    s.split_whitespace().map(str::to_string).collect()
}

/// The token lists the matcher looks at: the base variant, and the substitution variant when
/// it differs.
pub fn normalize(s: &str) -> Vec<Vec<String>> {
    let base = tokens(&base_text(s));
    let leet = tokens(&leet_text(s));
    if leet == base {
        vec![base]
    } else {
        vec![base, leet]
    }
}

/// Every 1-, 2- and 3-gram of `toks`, tokens joined by one space.
pub fn ngrams(toks: &[String]) -> Vec<String> {
    let mut out = Vec::with_capacity(toks.len() * MAX_NGRAM);
    for i in 0..toks.len() {
        let mut g = String::new();
        for (n, t) in toks[i..].iter().take(MAX_NGRAM).enumerate() {
            if n > 0 {
                g.push(' ');
            }
            g.push_str(t);
            out.push(g.clone());
        }
    }
    out
}

/// An age below [`AGE_LIMIT`] written next to an age marker: `12 yo`, `12yo`, `12 y o`,
/// `12 years old`, `12 yrs`, `aged 12`, `age 12`, French `12 ans`, German `12 jahre`, Spanish /
/// Portuguese `12 anos` (folded). Only applied to adult torrents.
pub fn age_rule(toks: &[String]) -> bool {
    let minor = |t: &str| -> bool {
        t.len() <= 2
            && t.bytes().all(|b| b.is_ascii_digit())
            && t.parse::<u32>().is_ok_and(|n| (1..AGE_LIMIT).contains(&n))
    };
    let glued = |t: &str| -> bool {
        let digits: String = t.chars().take_while(|c| c.is_ascii_digit()).collect();
        let rest = &t[digits.len()..];
        !digits.is_empty() && minor(&digits) && matches!(rest, "yo" | "yrs" | "yr" | "yearold")
    };
    for (i, t) in toks.iter().enumerate() {
        if glued(t) {
            return true;
        }
        let next = |k: usize| toks.get(i + k).map(String::as_str);
        if minor(t) {
            match next(1) {
                Some("yo" | "yrs" | "yr" | "ans" | "jahre" | "anos") => return true,
                Some("y") if next(2) == Some("o") => return true,
                Some("years" | "year") if next(2) == Some("old") => return true,
                _ => {}
            }
        }
        if matches!(t.as_str(), "aged" | "age") && next(1).is_some_and(minor) {
            return true;
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;

    // Neutral placeholder terms only (docs/DHT.md §7: no real term list in tests).
    fn list() -> Blocklist {
        Blocklist {
            version: 7,
            ..Default::default()
        }
        .with_extra("# test list\nzorblax\nquux frobnitz\ncontext:wibblewob\ncontext: plonk zap\n")
        .unwrap()
    }

    #[test]
    fn builtin_loads() {
        let b = Blocklist::builtin().expect("built-in list");
        let (hard, context) = b.len();
        assert!(hard > 0 && context > 0, "{hard} {context}");
        assert_eq!(b.version(), BUILTIN_VERSION);
        assert!(global().is_some());
    }

    #[test]
    fn hash_format_matches_the_script() {
        // printf 'magnetar-blocklist-v1:zorblax' | sha256sum (what scripts/blocklist-hash.sh does)
        assert_eq!(
            hex::encode(term_hash("zorblax")),
            "14613839473449239fa2ed21ecac3679fd5487e6dc9e06f2b992eafc91d0ee98"
        );
        assert_eq!(
            hex::encode(term_hash("quux frobnitz")),
            "37bf309341282bc84db760e2115a2487bf41621c92b4d23ab536f8b919e6c047"
        );
        // A hashed list in the terms.v1 format behaves like the plain one.
        let b = Blocklist::parse_hashed(
            "# x\nhard 14613839473449239fa2ed21ecac3679fd5487e6dc9e06f2b992eafc91d0ee98\n",
            3,
        )
        .unwrap();
        let none: [&str; 0] = [];
        assert!(b.check(&["a.zorblax.b"], &none, false).is_block());
        assert_eq!(b.version(), 3);
    }

    #[test]
    fn hard_terms_block_alone_in_every_variant() {
        let b = list();
        let none: [&str; 0] = [];
        let block = |s: &str| b.check(&[s], &none, false);
        assert_eq!(block("Some.Zorblax.2024"), Verdict::Block(Tier::Hard));
        assert_eq!(block("ZÖRBLÄX"), Verdict::Block(Tier::Hard), "diacritics");
        assert_eq!(
            block("z0rbl4x"),
            Verdict::Block(Tier::Hard),
            "substitutions"
        );
        assert_eq!(
            block("dir/sub_zorblax-file.mkv"),
            Verdict::Block(Tier::Hard)
        );
        assert_eq!(block("quux_frobnitz"), Verdict::Block(Tier::Hard), "bigram");
        assert_eq!(block("[quux](frobnitz)"), Verdict::Block(Tier::Hard));
        assert_eq!(block("quux and frobnitz"), Verdict::Allow, "not adjacent");
        assert_eq!(block("zorblaxed"), Verdict::Allow, "whole tokens only");
        assert_eq!(block("harmless name"), Verdict::Allow);
        // Any one of many names is enough (padding paths, name.utf-8, …).
        let names = ["fine", "also fine", "x/.pad/zorblax"];
        assert!(b.check(&names, &none, false).is_block());
    }

    #[test]
    fn context_terms_need_an_adult_torrent() {
        let b = list();
        let none: [&str; 0] = [];
        assert_eq!(b.check(&["wibblewob"], &none, false), Verdict::Allow);
        assert_eq!(
            b.check(&["wibblewob"], &none, true),
            Verdict::Block(Tier::Context)
        );
        assert_eq!(
            b.check(&["Plonk.Zap.mp4"], &none, true),
            Verdict::Block(Tier::Context)
        );
        assert_eq!(b.check(&["plonk"], &none, true), Verdict::Allow);
    }

    #[test]
    fn hard_only_texts_skip_the_context_tier() {
        let b = list();
        assert_eq!(
            b.check(&["title"], &["a long description with zorblax"], false),
            Verdict::Block(Tier::Hard)
        );
        assert_eq!(b.check(&["title"], &["wibblewob"], true), Verdict::Allow);
        assert_eq!(b.check(&["title"], &["14 yo"], true), Verdict::Allow);
    }

    #[test]
    fn age_rule_only_for_minors_in_adult_torrents() {
        let t = |s: &str| tokens(&base_text(s));
        for s in [
            "x 12 yo y",
            "x.12yo",
            "x 9 y.o.",
            "x 15 years old",
            "aged 13",
            "16 ans",
            "x-17-yrs",
        ] {
            assert!(age_rule(&t(s)), "{s}");
        }
        for s in [
            "18 yo",
            "18yo",
            "25 years old",
            "10 years",
            "120 yo",
            "age of empires",
            "2012 yo",
        ] {
            assert!(!age_rule(&t(s)), "{s}");
        }
        let b = list();
        let none: [&str; 0] = [];
        assert_eq!(b.check(&["clip 12 yo"], &none, false), Verdict::Allow);
        assert_eq!(
            b.check(&["clip 12 yo"], &none, true),
            Verdict::Block(Tier::Age)
        );
    }

    #[test]
    fn loading_is_strict_and_never_echoes_lines() {
        assert_eq!(
            Blocklist::parse_hashed("", 1).unwrap_err(),
            LoadError::Empty
        );
        assert_eq!(
            Blocklist::parse_hashed("hard nothex", 1).unwrap_err(),
            LoadError::BadLine(1)
        );
        assert_eq!(
            Blocklist::parse_hashed(&format!("# c\nsoft {}", "00".repeat(32)), 1).unwrap_err(),
            LoadError::BadLine(2)
        );
        let mut b = Blocklist::default();
        assert_eq!(b.add_plain("a b c d").unwrap_err(), LoadError::BadLine(1));
        assert_eq!(b.add_plain("---").unwrap_err(), LoadError::BadLine(1));
        assert_eq!(
            LoadError::BadLine(3).to_string(),
            "blocklist: malformed line 3"
        );
        let dbg = format!("{:?}", list());
        assert!(!dbg.contains("zorblax") && dbg.contains("hard: 2"), "{dbg}");
    }

    #[test]
    fn ngrams_and_variants() {
        let toks = tokens("a b c d");
        assert_eq!(
            ngrams(&toks),
            vec!["a", "a b", "a b c", "b", "b c", "b c d", "c", "c d", "d"]
        );
        assert_eq!(normalize("Été_ŁÓDŹ"), vec![vec!["ete", "lodz"]]);
        assert_eq!(normalize("h3ll0"), vec![vec!["h3ll0"], vec!["hello"]]);
        assert_eq!(normalize("Straße"), vec![vec!["strasse"]]);
    }
}
