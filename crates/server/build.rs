//! Embeds the web UI (`web/`, D132) into the binary: writes `$OUT_DIR/web_assets.rs` with
//! `ASSETS` (path, MIME, bytes; sorted by path) and `VERSION` (FNV-1a 64 over every file).
//! Standard library only. A missing `web/` (a cargo-chef dependency layer) gives an empty table
//! and `VERSION = "none"`; the server then answers 404 for the UI and says so in the log.

#[path = "src/web_build.rs"]
#[allow(dead_code)]
mod web_build;

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("web_assets.rs");
    let root = manifest.join("web");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/web_build.rs");
    let mut code = String::from("// @generated by build.rs (web UI assets, D132)\n");
    if !root.is_dir() {
        // Rerun once the directory appears.
        println!("cargo:rerun-if-changed=web");
        code.push_str("pub static ASSETS: &[(&str, &str, &[u8])] = &[];\n");
        code.push_str("pub const VERSION: &str = \"none\";\n");
        std::fs::write(&out, code).expect("write web_assets.rs");
        return;
    }
    println!("cargo:rerun-if-changed=web");
    let files = match web_build::collect(&root) {
        Ok(f) => f,
        Err(e) => panic!("{e}"),
    };
    let mut contents = Vec::with_capacity(files.len());
    for (rel, abs) in &files {
        println!("cargo:rerun-if-changed={}", abs.display());
        let bytes =
            std::fs::read(abs).unwrap_or_else(|e| panic!("web UI file {}: {e}", abs.display()));
        contents.push((rel.as_str(), bytes));
    }
    let version = web_build::version(contents.iter().map(|(p, b)| (*p, b.as_slice())));
    code.push_str("pub static ASSETS: &[(&str, &str, &[u8])] = &[\n");
    for (rel, abs) in &files {
        let mime = web_build::mime_for(rel).expect("checked by collect");
        let abs = abs
            .to_str()
            .unwrap_or_else(|| panic!("{}: path is not UTF-8", abs.display()));
        writeln!(code, "    ({rel:?}, {mime:?}, include_bytes!({abs:?})),").unwrap();
    }
    code.push_str("];\n");
    writeln!(code, "pub const VERSION: &str = {version:?};").unwrap();
    std::fs::write(&out, code).expect("write web_assets.rs");
}
