#!/usr/bin/env bash
# Generate crates/core/src/blocklist/terms.v1 (ARCHITECTURE.md D53, D68; docs/DHT.md §7.2) from a
# plain-text term list that is NOT committed: the repository carries hashes only.
#
#   scripts/blocklist-hash.sh <plain-list> > crates/core/src/blocklist/terms.v1
#
# Input: one term per line, `hard <phrase>` or `context <phrase>`; `#` comments. A phrase is
# 1-3 ASCII words (letters/digits; any other character separates words, as the Rust
# normaliser does). Non-ASCII terms are refused (the shell cannot reproduce Unicode folding:
# put them in MAGNETAR_BLOCKLIST_FILE, which the server normalises itself).
# Output: `hard|context <sha256 hex>` with sha256("magnetar-blocklist-v1:" + words joined by one
# space), sorted, after a header. Nothing is echoed to stderr but line numbers.
set -euo pipefail
src=${1:?usage: blocklist-hash.sh <plain-list>}
prefix='magnetar-blocklist-v1:'
out=$(mktemp "${XDG_CACHE_HOME:-$HOME/.cache}/blocklist-hash.XXXXXX")
trap 'rm -f "$out"' EXIT
n=0
while IFS= read -r line || [ -n "$line" ]; do
    n=$((n + 1))
    line=${line%%#*}
    line=$(printf '%s' "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
    [ -z "$line" ] && continue
    tier=${line%% *}
    phrase=${line#* }
    case $tier in hard | context) ;; *) echo "line $n: tier must be hard or context" >&2; exit 1 ;; esac
    if LC_ALL=C grep -q '[^ -~]' <<<"$phrase"; then
        echo "line $n: non-ASCII term (use MAGNETAR_BLOCKLIST_FILE)" >&2
        exit 1
    fi
    norm=$(printf '%s' "$phrase" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9' ' ' | tr -s ' ' | sed 's/^ //;s/ $//')
    words=$(wc -w <<<"$norm")
    if [ "$words" -lt 1 ] || [ "$words" -gt 3 ]; then
        echo "line $n: a term has 1-3 words" >&2
        exit 1
    fi
    h=$(printf '%s%s' "$prefix" "$norm" | sha256sum | cut -d' ' -f1)
    printf '%s %s\n' "$tier" "$h" >>"$out"
done <"$src"
cat <<'EOF'
# Magnetar hard illegal-content blocklist, version 1 (ARCHITECTURE.md D53, D68).
# Format: `hard|context <sha256("magnetar-blocklist-v1:" + normalised phrase)>`.
# Generated by scripts/blocklist-hash.sh from a plain list that is deliberately not committed.
# Seed: bitmagnet `keywords.banned` (classifier.core.yml at e31b30d, MIT licence,
# https://github.com/bitmagnet-io/bitmagnet), regex alternatives expanded to word forms,
# plus additions; two short seed terms are in the context tier (docs/DHT.md §7.2).
EOF
sort -u "$out"
